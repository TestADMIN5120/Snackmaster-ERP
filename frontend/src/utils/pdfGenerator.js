/* ──────────────────────────────────────────────
   🟢 NEW: MACHINE SLOT AUDIT PDF
────────────────────────────────────────────── */
export function generateMachineSlotPDF(machine, slots) {
  const doc = new jsPDF();

  doc.setFontSize(22);
  doc.setTextColor(15, 23, 42);
  doc.text("SNACKMASTER", 14, 22);

  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139);
  doc.text(`Machine ID: ${machine.id}`, 14, 28);
  doc.text(`Location: ${machine.location || "N/A"}`, 14, 33);

  doc.setFontSize(16);
  doc.setTextColor(14, 165, 233);
  doc.text(
    `MACHINE SLOT CONFIGURATION - ${machine.name || "AUDIT"}`,
    14,
    45
  );

  const tableData = slots.map((s) => {
    const code =
      110 + (Number(s.tray) - 1) * 10 + Number(s.slot_number);
    return [
      String(code),
      s.product_name || "EMPTY",
      s.current_qty.toString(),
      s.capacity.toString(),
      `${Math.round((s.current_qty / s.capacity) * 100)}%`
    ];
  });

  autoTable(doc, {
    startY: 55,
    head: [["Slot Code", "Product Name", "Current Qty", "Capacity", "Fill %"]],
    body: tableData,
    theme: "grid",
    headStyles: { fillColor: [14, 165, 233], textColor: 255 },
    styles: { fontSize: 10 }
  });

  const finalY = doc.lastAutoTable.finalY + 15;
  doc.setFontSize(8);
  doc.setTextColor(150);
  doc.text(
    `Generated on ${new Date().toLocaleString("en-IN")}`,
    14,
    finalY
  );

  doc.save(`Machine_Audit_${machine.id}.pdf`);
}