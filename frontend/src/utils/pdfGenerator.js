import jsPDF from "jspdf";
import autoTable from "jspdf-autotable"; // 🟢 FIXED IMPORT

/* ──────────────────────────────────────────────
   KIT MANIFEST PDF
────────────────────────────────────────────── */
export function generateKitPDF(kit) {
  if (!kit) return;
  const doc = new jsPDF();

  doc.setFontSize(22);
  doc.setTextColor(15, 23, 42);
  doc.text("SNACKMASTER", 14, 22);
  
  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139);
  doc.text("Automated Inventory Traceability System", 14, 28);

  doc.setFontSize(16);
  doc.setTextColor(14, 165, 233);
  doc.text("INVENTORY REFILL MANIFEST", 14, 40);

  doc.setFontSize(11);
  doc.setTextColor(51, 65, 85);
  
  const formatDate = (ts) => {
    if (!ts) return "N/A";
    const date = ts.seconds ? new Date(ts.seconds * 1000) : new Date(ts);
    return date.toLocaleString("en-IN", {
      dateStyle: "medium",
      timeStyle: "short"
    });
  };

  doc.text(`Manifest ID: ${kit.id}`, 14, 50);
  doc.text(`Date Prepared: ${formatDate(kit.createdAt)}`, 14, 56);
  doc.text(`Status: ${kit.status.toUpperCase()}`, 14, 62);

  doc.text(`Machine ID: ${kit.machineId}`, 120, 50);
  doc.text(`Refiller: ${kit.refillerEmail}`, 120, 56);
  doc.text(`Org ID: ${kit.orgId}`, 120, 62);

  const tableData = kit.products.map((p) => [
    p.slotId,
    p.name + (p.swapped ? " (Swapped)" : ""),
    p.requiredQty.toString(),
    "[   ]"
  ]);

  autoTable(doc, {
    startY: 70,
    head: [["Slot", "Product Item", "Qty", "Packed"]],
    body: tableData,
    theme: "grid",
    headStyles: {
      fillColor: [15, 23, 42],
      textColor: 255,
      fontStyle: "bold"
    },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    styles: { fontSize: 10, cellPadding: 6 },
    columnStyles: {
      0: { fontStyle: "bold", halign: "center", cellWidth: 30 },
      2: {
        fontStyle: "bold",
        halign: "center",
        textColor: [22, 163, 74],
        cellWidth: 30
      },
      3: { halign: "center", cellWidth: 30 }
    }
  });

  const finalY = doc.lastAutoTable.finalY + 15;
  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139);

  doc.text("Authorized Signature: _______________________", 14, finalY);
  doc.text("Refiller Signature: _______________________", 120, finalY);

  doc.setFontSize(8);
  doc.text(
    `Generated by SnackMaster System on ${new Date().toLocaleString("en-IN")}`,
    14,
    finalY + 15
  );
  doc.text("Confidential & Traceable Artifact", 14, finalY + 20);

  doc.save(`Kit_Manifest_${kit.machineId}_${kit.id.slice(-6)}.pdf`);
}

